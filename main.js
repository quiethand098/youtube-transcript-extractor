const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const dec = (s) => s.replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16))).replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d))
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&');
const idOf = (s) => {
  s = s.trim();
  if (/^[\w-]{11}$/.test(s)) return s;
  const m = s.match(/(?:v=|youtu\.be\/|\/shorts\/|\/embed\/|\/live\/)([\w-]{11})/);
  return m ? m[1] : null;
};

async function player(videoId) {
  const r = await pfetch(`https://www.youtube.com/youtubei/v1/player?key=${KEY}`, {
    method: 'POST', headers: { 'Content-Type': 'application/json', 'User-Agent': 'com.google.android.youtube/20.10.38 (Linux; U; Android 14)' },
    body: JSON.stringify({ context: { client: { clientName: 'ANDROID', clientVersion: '20.10.38', hl: 'en' } }, videoId }),
  });
  const txt = await r.text();
  try { return JSON.parse(txt); } catch { throw new Error(`YouTube blocked the request (HTTP ${r.status})`); }
}

async function playlistIds(url) {
  const list = url.match(/[?&]list=([\w-]+)/)?.[1];
  const html = await (await pfetch(`https://www.youtube.com/playlist?list=${list}`, { headers: { 'User-Agent': UA, 'Accept-Language': 'en-US', Cookie: 'CONSENT=YES+1' } })).text();
  return [...new Set([...html.matchAll(/"videoId":"([\w-]{11})"/g)].map((m) => m[1]))].slice(0, 100);
}

function chunk(segments, size) {
  const out = []; let cur = null;
  for (const s of segments) {
    if (!cur) cur = { start: s.start, text: '' };
    cur.text += (cur.text ? ' ' : '') + s.text;
    if (cur.text.length >= size && /[.!?]$/.test(s.text) || cur.text.length >= size * 1.5) { out.push(cur); cur = null; }
  }
  if (cur) out.push(cur);
  return out;
}

